// [EN] Script for data input and output
#include <iostream>
using namespace std;

int main() {
    int num1, num2;

    cout << "Enter the first number: ";
    cin >> num1;
    
    cout << "Enter the second number: ";
    cin >> num2;

    cout << "\nThe first number is: " << num1;
    cout << "\nThe second number is: " << num2;

    return 0;
}

